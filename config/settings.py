def env_bool(name, default=False):
    value = os.environ.get(name, str(default)).strip().lower()
    if value not in {'true', 'false', '1', '0'}:
        raise ImproperlyConfigured(f'{name}: ожидается True/False или 1/0.')
    return value in {'true', '1'}


